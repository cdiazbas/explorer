#!/usr/bin/env python3
"""src/explorer/platform/xbridge/keysyms.py from X.Org's keysymdef.h: the character each legacy keysym types.

    python3 scripts/gen_keysyms.py /opt/X11/include/X11/keysymdef.h       # XQuartz's; /usr/include/X11/ on Linux

The legacy keysyms are those of Latin-2 to 4, Cyrillic, Greek, Hebrew, the euro sign...: the keys of a Serbian or
Czech keyboard, not their code points. keysymdef.h notes the code point of each one-to-one keysym as /* U+XXXX */;
those noted in parentheses or angle brackets (approximate, or another keysym's) are left out, and so are Latin-1 and
Unicode keysyms (keys.keysym_char reads those from the number) and the function and keypad keys (0xfd00 on:
keys.SPECIAL). keysymdef.h's licence asks for its notice in every copy: the generated file carries it.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/explorer/platform/xbridge/keysyms.py"
DEFINE = re.compile(r"^#define XK_\w+\s+0x([0-9a-fA-F]+)\s*/\* U\+([0-9A-Fa-f]{4,6}) ")


def main(src: str) -> None:
    text = Path(src).read_text()
    notice = text[text.index("/*") + 2:text.index("*/")].strip("*\n")
    table: dict[int, int] = {}
    for line in text.splitlines():
        m = DEFINE.match(line)
        if not m:
            continue
        sym, cp = int(m.group(1), 16), int(m.group(2), 16)
        if sym >= 0xFD00 or 0x20 <= sym <= 0x7E or 0xA0 <= sym <= 0xFF:
            continue
        table.setdefault(sym, cp)
    rows = sorted(table.items())
    lines = ['"""The character each legacy keysym types (Latin-2 to 4, Cyrillic, Greek, Hebrew, the euro sign...):',
             "keysym -> code point. Generated by scripts/gen_keysyms.py from X.Org's keysymdef.h, whose notice",
             "follows.",
             "", *("    " + n.rstrip() if n.strip() else "" for n in notice.splitlines()), '"""', "", "UCS = {"]
    lines += ["    " + " ".join(f"0x{s:x}: 0x{c:04x}," for s, c in rows[i:i + 6]) for i in range(0, len(rows), 6)]
    OUT.write_text("\n".join(lines) + "\n}\n")
    print(f"{OUT}: {len(rows)} keysyms")


if __name__ == "__main__":
    main(sys.argv[1])
